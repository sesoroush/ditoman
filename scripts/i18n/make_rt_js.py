#!/usr/bin/env python3
"""Writes i18n-zh.js / i18n-tr.js / i18n-ru.js: the runtime translator for text that scripts write after the
page loads (price strip, quiz, charts, search). Dictionary = short strings of data/i18n/src/<lang>-*.json plus
every string listed in data/i18n/work/rt.json (script strings of any length)."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "scripts" / "i18n"))
import lang_rules

MONTHS = {
    "zh": ["1月", "2月", "3月", "4月", "5月", "6月", "7月", "8月", "9月", "10月", "11月", "12月"],
    "tr": ["Oca", "Şub", "Mar", "Nis", "May", "Haz", "Tem", "Ağu", "Eyl", "Eki", "Kas", "Ara"],
    "ru": ["янв.", "февр.", "мар.", "апр.", "мая", "июн.", "июл.", "авг.", "сент.", "окт.", "нояб.", "дек."],
}
FMT = {  # d = day, m = month name, y = year
    "zh": ("{y}年{mn}月{d}日", "{y}年{mn}月"),
    "tr": ("{d} {m} {y}", "{m} {y}"),
    "ru": ("{d} {m} {y}", "{m} {y}"),
}
REPORT = {"zh": "每日市场报告 {d}", "tr": "Günlük piyasa raporu {d}", "ru": "Ежедневный обзор рынка {d}"}
UPDATED = {"zh": "更新于：", "tr": "Güncelleme: ", "ru": "Обновлено: "}
POOL = {"zh": "），更新于 {t}。", "tr": "), güncelleme {t}.", "ru": "), обновлено {t}."}

JS = r'''/* %(lang)s pages (X.%(lang)s.html): translates the English text that scripts write after the page loads
   (price strip, quiz, charts, search). Page text itself is translated at build time by scripts/build_lang_pages.py.
   Generated by scripts/i18n/make_rt_js.py from data/i18n/src/%(lang)s-*.json. */
(function () {
  var root = document.documentElement;
  if (root.getAttribute("data-site-lang") !== "%(lang)s") return;
  var D = %(dict)s;
  var MON = %(mon)s, MN = {Jan:0,Feb:1,Mar:2,Apr:3,May:4,Jun:5,Jul:6,Aug:7,Sep:8,Oct:9,Nov:10,Dec:11};
  var DATE = %(date)s, MONTH = %(month)s, REPORT = %(report)s, UPDATED = %(updated)s;
  var POOL = %(pool)s, READ = %(read)s, MINS = %(mins)s, STEP = %(step)s;
  function fmt(t, o) { return t.replace(/\{(\w+)\}/g, function (_, k) { return o[k]; }); }
  function rule(t) {
    var m;
    if ((m = t.match(/^(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})$/))) return fmt(DATE, { d: m[1], m: MON[MN[m[2]]], mn: MN[m[2]] + 1, y: m[3] });
    if ((m = t.match(/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})$/))) return fmt(MONTH, { m: MON[MN[m[1]]], mn: MN[m[1]] + 1, y: m[2] });
    if ((m = t.match(/^Daily market report (\d{4}-\d{2}-\d{2})$/))) return fmt(REPORT, { d: m[1] });
    if ((m = t.match(/^Updated: (.+)$/))) return UPDATED + m[1];
    if ((m = t.match(/^\), updated (.+?)\.?$/))) return fmt(POOL, { t: m[1] });
    if ((m = t.match(/^(\d+) min read$/))) return fmt(READ, { n: m[1] });
    if ((m = t.match(/^(\d+) min$/))) return fmt(MINS, { n: m[1] });
    if ((m = t.match(/^Step (\d+)$/))) return fmt(STEP, { n: m[1] });
    return null;
  }
  var LAT = /[A-Za-z]{2}/;
  function tr(s) {
    var t = s.replace(/\s+/g, " ").trim();
    if (!t || !LAT.test(t)) return null;
    var out = D[t];
    if (out == null) out = rule(t);
    if (out == null || out === t) return null;
    return s.match(/^\s*/)[0] + out + s.match(/\s*$/)[0];
  }
  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEXTAREA: 1, CODE: 1, PRE: 1 };
  function walk(node) {
    if (node.nodeType === 3) { var o = tr(node.nodeValue); if (o != null && o !== node.nodeValue) node.nodeValue = o; return; }
    if (node.nodeType !== 1 || SKIP[node.nodeName] || node.getAttribute("translate") === "no") return;
    ["aria-label", "placeholder", "title", "alt"].forEach(function (a) {
      var v = node.getAttribute && node.getAttribute(a);
      if (v && LAT.test(v)) { var o = tr(v); if (o != null) node.setAttribute(a, o); }
    });
    for (var c = node.firstChild; c; c = c.nextSibling) walk(c);
  }
  function run() { walk(document.body); }
  run();
  var busy = false;
  new MutationObserver(function (list) {
    if (busy) return; busy = true;
    list.forEach(function (m) {
      if (m.type === "characterData") walk(m.target);
      else { m.addedNodes.forEach(walk); if (m.type === "attributes") walk(m.target); }
    });
    busy = false;
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "placeholder", "title"] });
})();
'''

rt = set(json.loads((ROOT / "data/i18n/work/rt.json").read_text(encoding="utf-8")))
for lang in ("zh", "tr", "ru"):
    srcs = sorted((ROOT / "data/i18n/src").glob(f"{lang}-*.json"))
    if not srcs:
        continue
    core = {}
    for f in srcs:
        core.update(json.loads(f.read_text(encoding="utf-8")))
    ui = set()
    for f in srcs:
        if f.name.endswith("-ui.json"):
            ui |= set(json.loads(f.read_text(encoding="utf-8")))
    D = {k: v for k, v in core.items() if (len(k) <= 56 or k in rt or k in ui) and "<" not in k and k != v}
    r = lang_rules.R[lang]
    date, month = FMT[lang]
    out = JS % dict(lang=lang, dict=json.dumps(D, ensure_ascii=False, separators=(",", ":")), mon=json.dumps(MONTHS[lang], ensure_ascii=False),
                    date=json.dumps(date, ensure_ascii=False), month=json.dumps(month, ensure_ascii=False), report=json.dumps(REPORT[lang], ensure_ascii=False),
                    updated=json.dumps(UPDATED[lang], ensure_ascii=False), pool=json.dumps(POOL[lang], ensure_ascii=False),
                    read=json.dumps(r["read"]("{n}"), ensure_ascii=False), mins=json.dumps(r["mins"]("{n}"), ensure_ascii=False), step=json.dumps(r["step"]("{n}"), ensure_ascii=False))
    (ROOT / f"i18n-{lang}.js").write_text(out, encoding="utf-8")
    print(f"i18n-{lang}.js", len(D), "strings", len(out) // 1024, "KB")
